-- Clean-install baseline for the current Order Service. It incorporates the
-- final schema represented by migrations/001 and 002; do not run those upgrade
-- files against a database initialized from this baseline.
BEGIN;

CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL,
    total_amount NUMERIC NOT NULL,
    status CHARACTER VARYING NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX orders_user_id_idx ON public.orders (user_id, id);

CREATE TABLE public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    price NUMERIC NOT NULL
);

CREATE INDEX order_items_order_id_idx ON public.order_items (order_id);

CREATE TABLE public.order_idempotency (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL CHECK (user_id > 0),
    key_digest BYTEA NOT NULL CHECK (octet_length(key_digest) = 32),
    request_digest BYTEA NOT NULL CHECK (octet_length(request_digest) = 32),
    request_payload JSONB NOT NULL CHECK (jsonb_typeof(request_payload) = 'object'),
    reservation_ids JSONB NOT NULL CHECK (jsonb_typeof(reservation_ids) = 'array'),
    state TEXT NOT NULL CHECK (state IN (
        'IN_PROGRESS', 'RECOVERY_REQUIRED', 'COMPLETED', 'FAILED'
    )),
    response_status SMALLINT,
    response_body JSONB,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_id BIGINT,
    CONSTRAINT order_idempotency_user_key_unique UNIQUE (user_id, key_digest),
    CONSTRAINT order_idempotency_order_id_fkey
        FOREIGN KEY (order_id) REFERENCES public.orders(id),
    CONSTRAINT order_idempotency_response_state_check CHECK (
        (
            state IN ('COMPLETED', 'FAILED')
            AND response_status IS NOT NULL
            AND response_status BETWEEN 100 AND 599
            AND response_body IS NOT NULL
            AND jsonb_typeof(response_body) = 'object'
        )
        OR
        (
            state IN ('IN_PROGRESS', 'RECOVERY_REQUIRED')
            AND response_status IS NULL
            AND response_body IS NULL
        )
    )
);

CREATE INDEX order_idempotency_pending_recovery_idx
    ON public.order_idempotency (updated_at)
    WHERE state IN ('IN_PROGRESS', 'RECOVERY_REQUIRED');

CREATE TABLE public.reconciliation_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id UUID NOT NULL,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    action TEXT NOT NULL CHECK (action IN ('RELEASE')),
    status TEXT NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_retry_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT reconciliation_tasks_reservation_action_unique
        UNIQUE (reservation_id, action)
);

CREATE INDEX reconciliation_tasks_pending_idx
    ON public.reconciliation_tasks (next_retry_at, id)
    WHERE status = 'PENDING';

CREATE TABLE public.order_service_schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.order_service_schema_migrations (version)
VALUES ('001_order_idempotency'), ('002_order_idempotency_order_id');

COMMIT;
