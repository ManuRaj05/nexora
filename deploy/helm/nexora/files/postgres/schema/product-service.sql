-- Clean-install schema for the Product Service. This includes the final
-- reservation fencing ledger represented by migrations/001_reservation_operations.sql.
BEGIN;

CREATE TABLE public.products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name CHARACTER VARYING NOT NULL,
    description TEXT NOT NULL,
    price NUMERIC NOT NULL,
    stock INTEGER NOT NULL,
    category CHARACTER VARYING NOT NULL
);

CREATE TABLE public.stock_reservations (
    reservation_id UUID PRIMARY KEY,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    status CHARACTER VARYING NOT NULL
        CHECK (status IN ('RESERVED', 'RELEASED')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.reservation_operations (
    reservation_id UUID PRIMARY KEY,
    product_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    fencing_generation BIGINT NOT NULL CHECK (fencing_generation >= 0),
    status TEXT NOT NULL
        CHECK (status IN ('RESERVED', 'RELEASED', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.product_service_schema_migrations (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO public.product_service_schema_migrations (version)
VALUES ('001_reservation_operations');

COMMIT;
