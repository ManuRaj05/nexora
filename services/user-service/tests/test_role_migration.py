import unittest
from pathlib import Path


MIGRATION = Path(__file__).resolve().parents[1] / "migrations" / "001_user_roles.sql"


class UserRoleMigrationTests(unittest.TestCase):
    def test_upgrade_defaults_new_users_and_preserves_valid_administrators(self):
        sql = MIGRATION.read_text().upper()
        self.assertIn("ALTER COLUMN ROLE SET DEFAULT 'CUSTOMER'", sql)
        self.assertIn("WHERE ROLE IS NULL OR ROLE NOT IN ('CUSTOMER', 'ADMIN')", sql)
        self.assertIn("CHECK (ROLE IN ('CUSTOMER', 'ADMIN'))", sql)
        self.assertIn("ALTER COLUMN ROLE SET NOT NULL", sql)

    def test_clean_install_schema_matches_verified_table_shape(self):
        sql = (MIGRATION.parents[1] / "schema.sql").read_text().upper()
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", sql)
        self.assertIn("CREATED_AT TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP", sql)
        self.assertIn("ROLE CHARACTER VARYING DEFAULT 'CUSTOMER'::CHARACTER VARYING NOT NULL", sql)
        self.assertIn("CONSTRAINT USERS_ROLE_CHECK", sql)

    def test_migration_is_repeatable_and_does_not_drop_or_delete_user_data(self):
        sql = MIGRATION.read_text().upper()
        self.assertIn("IF NOT EXISTS", sql)
        self.assertNotIn("DELETE FROM USERS", sql)
        self.assertNotIn("DROP TABLE", sql)
        self.assertNotIn("TRUNCATE", sql)


if __name__ == "__main__":
    unittest.main()
