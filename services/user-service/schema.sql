-- Clean-install schema for a new User Service database.
-- For legacy databases, use migrations/001_user_roles.sql instead.
BEGIN;

CREATE TABLE public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    username CHARACTER VARYING NOT NULL,
    email CHARACTER VARYING NOT NULL,
    password_hash CHARACTER VARYING NOT NULL,
    role CHARACTER VARYING DEFAULT 'CUSTOMER'::character varying NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_username_key UNIQUE (username),
    CONSTRAINT users_email_key UNIQUE (email),
    CONSTRAINT users_role_check
        CHECK (((role)::text = ANY (
            (ARRAY['CUSTOMER'::character varying, 'ADMIN'::character varying])::text[]
        )))
);

COMMIT;
